import type {
  AssessmentDetail,
  AssessmentJudgmentView,
  AssessmentListResponse,
  AssessmentRunView,
  DimensionReport,
  UnknownRecord,
} from '@judge-copilot/schemas';
import Link from 'next/link';
import type { ReactNode } from 'react';
import {
  classifyPage,
  explainFailure,
  formatCostNanoUsd,
  formatRatio,
  formatScore10,
  relativeDimensions,
  runToExplain,
  withheldGuidance,
  type RelativeEntry,
} from '../../../../lib/assessment-view';
import { ErrorBanner, formatDate } from '../../../components/ui';

/*
 * The presentation of the assessment page, separate from fetching so that it can be rendered in a test with plain data. It never
 * computes a number: every figure comes from the verified report in `detail`, and an unverified detail renders none of its content.
 */

export interface UnknownsView {
  readonly items: readonly UnknownRecord[];
  /** More unknowns exist than are listed. */
  readonly hasMore: boolean;
}

export interface AssessmentPageViewProps {
  readonly projectId: string;
  readonly projectName: string;
  readonly list: AssessmentListResponse;
  /** The detail of the version shown, or null. */
  readonly detail: AssessmentDetail | null;
  readonly detailError: string | undefined;
  readonly error: string | undefined;
  /** A fresh Idempotency-Key per rendered form (generated by the page). */
  /** The project's recorded unknowns (evidence graph), or null when they could not be loaded. Shown only for a verified assessment. */
  readonly unknowns: UnknownsView | null;
  readonly requestKeys: { readonly assess: string; readonly reassess: string };
  /** The form action (a server action in the app, a stub in tests). */
  readonly requestAction: (formData: FormData) => void | Promise<void>;
}

export function AssessmentPageView(props: AssessmentPageViewProps): ReactNode {
  const {
    projectId,
    projectName,
    list,
    detail,
    detailError,
    error,
    unknowns,
    requestKeys,
    requestAction,
  } = props;
  const base = `/projects/${encodeURIComponent(projectId)}`;
  const back = (
    <p>
      <Link href={base}>← {projectName}</Link>
    </p>
  );
  const state = classifyPage(list, detail);
  const run = runToExplain(list);

  return (
    <main>
      {back}
      <h1>Preliminary report</h1>
      <p className="notice" role="note">
        <strong>Advisory only.</strong> {list.notice} Nothing here is a final score.{' '}
        <strong>Preliminary:</strong> this report is built only from the submitted material, before
        any question is asked or answered.
      </p>
      <ErrorBanner message={error} />
      {detailError ? <ErrorBanner message={detailError} /> : null}

      <p data-state={state}>
        <span className="badge">{STATE_LABELS[state]}</span>
      </p>

      {run ? <RunPanel run={run} /> : null}
      {state === 'none' ? (
        <p>No assessment has been requested for this project yet. Nothing has been scored.</p>
      ) : null}
      {state === 'unverified' ? <WithheldPanel code={detail?.verificationFailure ?? null} /> : null}
      {detail && state !== 'unverified' ? (
        <AssessmentView detail={detail} unknowns={unknowns} />
      ) : null}

      <Launch
        projectId={projectId}
        launch={list.launch}
        hasAssessment={list.assessments.length > 0}
        newestWithheld={list.assessments[0]?.verified === false}
        activeRun={list.activeRun !== null}
        requestKeys={requestKeys}
        requestAction={requestAction}
      />

      {list.assessments.length > 1 ? (
        <section>
          <h2>Versions</h2>
          <ul>
            {list.assessments.map((item) => (
              <li key={item.id}>
                <Link href={`${base}/assessment?version=${item.id}`}>
                  Version {item.versionNumber}
                </Link>{' '}
                · {formatDate(item.createdAt)}
                {item.replayDemonstration ? ' · replay demonstration' : ''}
                {item.verified ? '' : ' · not verified'}
              </li>
            ))}
          </ul>
        </section>
      ) : null}
    </main>
  );
}

const ATTRIBUTION_LABELS = {
  scored: 'scored by the assessor',
  insufficient_by_assessor: 'insufficiency declared by the assessor (not independently reviewed)',
  insufficient_by_code: 'insufficiency found by deterministic code',
  insufficient_by_critic: 'score withdrawn after the critic’s blocking finding',
  technical: 'technical failure (not a judgment about the project)',
} as const;

const INSUFFICIENCY_LABELS = {
  assessor_reported_insufficient:
    'the assessor reported insufficient evidence, or code found no usable basis',
  no_usable_citation:
    'a value was judged but only absence, unknown or contradiction evidence was cited, so the scorer did not use it',
} as const;

const STATE_LABELS = {
  none: 'NO ASSESSMENT',
  in_progress: 'IN PROGRESS',
  run_failed: 'RUN DID NOT COMPLETE',
  unverified: 'NOT VERIFIED',
  scored: 'SCORED',
  scored_partial: 'PARTIALLY SCORED',
  insufficient_evidence: 'INSUFFICIENT EVIDENCE',
} as const;

function RunPanel({ run }: { run: AssessmentRunView }) {
  if (run.state === 'pending' || run.state === 'running') {
    return (
      <section>
        <h2>Run {run.state === 'pending' ? 'waiting for a worker' : 'in progress'}</h2>
        <p>
          Requested {formatDate(run.createdAt)}
          {run.stageReached ? ` · stage ${run.stageReached}` : ''}. Reload this page to refresh; no
          assessment exists until the run succeeds.
        </p>
      </section>
    );
  }
  return (
    <section>
      <h2>{run.state === 'cancelled' ? 'Run cancelled' : 'Run failed'}</h2>
      <p role="alert" className="error">
        {explainFailure(run)} No assessment was produced and no score is shown for this run.
      </p>
      <p>
        <small>
          {run.failureCategory ?? '—'}
          {run.failureCode ? ` · ${run.failureCode}` : ''}
          {run.stageReached ? ` · reached ${run.stageReached}` : ''} · finished{' '}
          {formatDate(run.finishedAt)}
        </small>
      </p>
    </section>
  );
}

function Launch({
  projectId,
  launch,
  hasAssessment,
  newestWithheld,
  activeRun,
  requestKeys,
  requestAction,
}: {
  projectId: string;
  launch: AssessmentListResponse['launch'];
  hasAssessment: boolean;
  /** The newest version failed verification: asking for "the assessment for the current material" would just point at it again. */
  newestWithheld: boolean;
  activeRun: boolean;
  requestKeys: AssessmentPageViewProps['requestKeys'];
  requestAction: AssessmentPageViewProps['requestAction'];
}) {
  return (
    <section>
      <h2>Run assessment</h2>
      <p>{launch.notice}</p>
      {!launch.available ? (
        <p role="status">
          Assessments cannot be run here: no approved offline replay mode is configured (
          <code>ASSESSMENT_PROVIDER_NOT_CONFIGURED</code>).
        </p>
      ) : activeRun ? (
        <p>A run is already active for this project.</p>
      ) : (
        <>
          {newestWithheld ? (
            <p role="status">
              The newest version is withheld (see above), so “show the assessment” would point at it
              again. “Reassess” creates a fresh version.
            </p>
          ) : (
            <form action={requestAction}>
              <input type="hidden" name="projectId" value={projectId} />
              <input type="hidden" name="requestKey" value={requestKeys.assess} />
              <input type="hidden" name="mode" value="assess" />
              <button type="submit">
                {hasAssessment ? 'Show assessment for current material' : 'Run assessment'}
              </button>
            </form>
          )}
          {hasAssessment ? (
            <form action={requestAction}>
              <input type="hidden" name="projectId" value={projectId} />
              <input type="hidden" name="requestKey" value={requestKeys.reassess} />
              <input type="hidden" name="mode" value="reassess" />
              <button type="submit">Reassess (creates a new version)</button>
            </form>
          ) : null}
        </>
      )}
    </section>
  );
}

function AssessmentView({
  detail,
  unknowns,
}: {
  detail: AssessmentDetail;
  unknowns: UnknownsView | null;
}) {
  const report = detail.report;
  if (!report) return null;
  const overall = report.overall;
  const judgmentByDimension = new Map(detail.judgments.map((j) => [j.dimensionId, j]));
  return (
    <>
      {detail.replayDemonstration ? (
        <p role="note" className="notice">
          <strong>Replay demonstration.</strong> {detail.notices.replay} These values come from
          recorded fixtures, not a live model, and say nothing about a real submission.
        </p>
      ) : null}
      <section>
        <h2>Overall (version {detail.versionNumber})</h2>
        {overall.state === 'scored' || overall.state === 'scored_partial' ? (
          <p>
            <strong>{formatScore10(overall.score10)} / 10</strong> ·{' '}
            {overall.state === 'scored_partial'
              ? `partial: based on ${formatRatio(overall.assessedWeightShare)} of the weight`
              : 'all weighted dimensions assessed'}{' '}
            · confidence index {formatRatio(overall.confidence)}
            {overall.coverage !== null ? ` · coverage ${formatRatio(overall.coverage)}` : ''}
            {overall.state === 'scored_partial' && overall.missingCriterionKeys.length > 0
              ? ` · not assessed: ${overall.missingCriterionKeys.join(', ')}`
              : ''}
          </p>
        ) : overall.state === 'insufficient_evidence' ? (
          <p>
            Insufficient evidence for an overall score. No number is given, and this is not a low
            score.
          </p>
        ) : (
          <p>
            No overall number is computed for an unweighted official rubric. Per-criterion results
            are shown below.
          </p>
        )}
        <p>
          <small>
            Rubric: {report.rubric.name} ({report.rubric.official ? 'official' : 'fallback'}).
            Confidence is an index, not a probability. Parameters are heuristic and uncalibrated.
            Assessment target: overall rubric only. Provider {detail.providerMode}.
          </small>
        </p>
      </section>

      <section>
        <h2>Criteria</h2>
        <table>
          <thead>
            <tr>
              <th>Criterion</th>
              <th>Result</th>
              <th>Confidence</th>
              <th>Coverage</th>
            </tr>
          </thead>
          <tbody>
            {report.criteria.map((criterion) => (
              <tr key={criterion.key}>
                <td>{criterion.name}</td>
                {criterion.state === 'assessed' || criterion.state === 'partial' ? (
                  <>
                    <td>
                      {formatScore10(criterion.score10)} / 10
                      {criterion.state === 'partial'
                        ? ` (partial; missing ${criterion.missingDimensionIds.join(', ')})`
                        : ''}
                    </td>
                    <td>{formatRatio(criterion.confidence)}</td>
                    <td>{criterion.coverage === null ? '—' : formatRatio(criterion.coverage)}</td>
                  </>
                ) : criterion.state === 'insufficient_evidence' ? (
                  <td colSpan={3}>Insufficient evidence (no number)</td>
                ) : (
                  <td colSpan={3}>Not applicable ({criterion.reason})</td>
                )}
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <RelativeSection report={report} judgments={detail.judgments} />

      <section>
        <h2>Dimensions</h2>
        {report.dimensions.map((dimension) => (
          <DimensionCard
            key={dimension.id}
            dimension={dimension}
            judgment={judgmentByDimension.get(dimension.id) ?? null}
          />
        ))}
      </section>

      <UnknownsSection report={report} detail={detail} unknowns={unknowns} />

      {detail.limitations.length > 0 ? (
        <section>
          <h2>Limitations</h2>
          <ul>
            {detail.limitations.map((item) => (
              <li key={item.code}>
                <code>{item.code}</code> ×{item.count}
                {item.subjects.length > 0 ? ` — ${item.subjects.join(', ')}` : ''}
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      <section>
        <h2>What this does not establish</h2>
        <ul>
          <li>
            Citation relevance is <strong>not verified</strong>: a cited item is not checked to
            support the claim it is attached to.
          </li>
          <li>
            The rationale, citation notes and limitation lists of each dimension are{' '}
            <strong>stored text that no integrity hash covers</strong>. The report’s numbers and
            states are verified; this text is shown as recorded and is not cryptographically
            authenticated.
          </li>
          <li>
            Scores are shown exactly as the verified report states them: the scoring engine rounds
            each score once, half-up, to four decimals (a raw 7.33333 is reported, and shown, as
            7.3333). Percentages (confidence index, coverage, shares) are rounded half-up to whole
            numbers for display only.
          </li>
          <li>Claim labels are never proof of truth; missing evidence is not negative evidence.</li>
          <li>Contradictions are only those recorded in the evidence graph.</li>
        </ul>
        <p>
          <small>
            Model usage (local counters): {detail.usage.settledCalls} settled call(s),{' '}
            {detail.usage.unknownCalls} unknown, {detail.usage.inputTokens} input /{' '}
            {detail.usage.outputTokens} output tokens, {formatCostNanoUsd(detail.usage.costNanoUsd)}
            .
          </small>
        </p>
      </section>
    </>
  );
}

function DimensionCard({
  dimension,
  judgment,
}: {
  dimension: DimensionReport;
  judgment: AssessmentJudgmentView | null;
}) {
  return (
    <div className="fact">
      <div>
        <strong>{dimension.name}</strong> <code>{dimension.id}</code>
      </div>
      <div>
        {dimension.state === 'assessed' ? (
          <>
            {formatScore10(dimension.score10)} / 10 · confidence {formatRatio(dimension.confidence)}{' '}
            · evidence strength {formatRatio(dimension.evidenceStrength)}
          </>
        ) : (
          <>
            Insufficient evidence ({INSUFFICIENCY_LABELS[dimension.reason]}) — no number is given.
          </>
        )}
      </div>
      {judgment ? (
        <>
          <div className="meta">
            {
              // an insufficient dimension shows WHO decided (the attribution), never the raw stored disposition: a judged value that
              // M4 did not use is stored as `scored`, and a `scored` tag next to "no number is given" would contradict the report
              dimension.state === 'assessed' ? (
                <span className="tag">{judgment.disposition}</span>
              ) : null
            }
            <span className="tag">{ATTRIBUTION_LABELS[judgment.dispositionAttribution]}</span>
            {judgment.criticReviewRequired ? (
              <span className="tag">
                {judgment.criticReviewed ? 'critic reviewed' : 'critic pending'}
              </span>
            ) : null}
            <span className="tag tag-warn">relevance not verified</span>
            <span className="tag tag-warn">
              rationale, notes and limitations: stored text, not hash-verified
            </span>
          </div>
          {judgment.rationale ? <p>{judgment.rationale}</p> : null}
          {judgment.limitations.length > 0 ? (
            <ul>
              {judgment.limitations.map((text) => (
                <li key={text}>{text}</li>
              ))}
            </ul>
          ) : null}
          {judgment.citations.length > 0 ? (
            <ul>
              {judgment.citations.map((citation) => (
                <li key={citation.evidenceId}>
                  <small>
                    {citation.evidence?.text ?? citation.evidenceId}
                    {citation.evidence
                      ? ` [${citation.evidence.kind} · ${citation.evidence.verificationLevel}]`
                      : ''}{' '}
                    — {citation.directness}, {citation.specificity}
                    {citation.note ? `: ${citation.note}` : ''}
                  </small>
                </li>
              ))}
            </ul>
          ) : (
            <p>
              <small>No citations.</small>
            </p>
          )}
        </>
      ) : null}
    </div>
  );
}

function WithheldPanel({ code }: { code: string | null }) {
  const guidance = withheldGuidance(code);
  return (
    <section aria-labelledby="withheld-heading">
      <h2 id="withheld-heading">This assessment is withheld</h2>
      <p role="alert" className="error">
        {guidance.reason} None of its content is shown here, including numbers.
        {code ? (
          <>
            {' '}
            Code: <code>{code}</code>.
          </>
        ) : null}
      </p>
      <p>{guidance.action}</p>
    </section>
  );
}

function EntryEvidence({ entry }: { entry: RelativeEntry }) {
  const citations = entry.judgment?.citations ?? [];
  const limitations = entry.judgment?.limitations ?? [];
  return (
    <>
      <small>
        confidence index {formatRatio(entry.confidence)} · {String(citations.length)} cited item
        {citations.length === 1 ? '' : 's'}
        {limitations.length > 0
          ? ` · limitations: ${limitations.join(', ')}`
          : ' · no dimension limitations recorded'}
      </small>
      {citations.length > 0 ? (
        <ul>
          {citations.slice(0, 2).map((citation) => (
            <li key={citation.evidenceId}>
              <small>
                {citation.evidence?.text ?? citation.evidenceId}
                {citation.evidence
                  ? ` [${citation.evidence.kind} · ${citation.evidence.verificationLevel}]`
                  : ''}
              </small>
            </li>
          ))}
          {citations.length > 2 ? (
            <li>
              <small>and {String(citations.length - 2)} more (see the dimension below)</small>
            </li>
          ) : null}
        </ul>
      ) : null}
    </>
  );
}

function RelativeList({ title, entries }: { title: string; entries: readonly RelativeEntry[] }) {
  return (
    <div>
      <h3>{title}</h3>
      <ul>
        {entries.map((entry) => (
          <li key={entry.dimensionId}>
            <strong>{entry.name}</strong> <code>{entry.dimensionId}</code> —{' '}
            {formatScore10(entry.score10)} / 10
            <br />
            <EntryEvidence entry={entry} />
          </li>
        ))}
      </ul>
    </div>
  );
}

function RelativeSection({
  report,
  judgments,
}: {
  report: NonNullable<AssessmentDetail['report']>;
  judgments: AssessmentDetail['judgments'];
}) {
  const relative = relativeDimensions(report, judgments);
  return (
    <section aria-labelledby="relative-heading" data-testid="relative-section">
      <h2 id="relative-heading">Relative highs and lows among assessed dimensions</h2>
      <p className="notice" role="note">
        This compares this project’s assessed dimensions <strong>with each other only</strong>. The
        highest is not necessarily strong and the lowest is not necessarily weak: it says nothing
        about other projects or about any standard, and a dimension without enough evidence is left
        out (it is not counted as zero).
      </p>
      {relative.kind === 'not_enough' ? (
        <p data-testid="relative-none">
          No comparison is shown: it needs at least two assessed dimensions, and this report has{' '}
          {String(relative.assessed)}.
        </p>
      ) : relative.kind === 'all_equal' ? (
        <p data-testid="relative-equal">
          All {String(relative.assessed)} assessed dimensions have the same score (
          {formatScore10(relative.score10)} / 10), so there is no highest or lowest.
        </p>
      ) : (
        <>
          <RelativeList
            title={`Highest-scoring assessed dimension${relative.highest.length > 1 ? 's (tied)' : ''}`}
            entries={relative.highest}
          />
          <RelativeList
            title={`Lowest-scoring assessed dimension${relative.lowest.length > 1 ? 's (tied)' : ''}`}
            entries={relative.lowest}
          />
        </>
      )}
      {relative.notAssessed > 0 ? (
        <p>
          <small>
            {String(relative.notAssessed)} dimension{relative.notAssessed === 1 ? '' : 's'} had too
            little evidence for a number and {relative.notAssessed === 1 ? 'is' : 'are'} not part of
            this comparison.
          </small>
        </p>
      ) : null}
    </section>
  );
}

const UNKNOWN_TYPE_LABEL: Readonly<Record<UnknownRecord['unknownType'], string>> = {
  missing: 'missing',
  ambiguous: 'ambiguous',
  contradictory: 'contradictory',
  unverifiable: 'cannot be verified',
  subjective: 'subjective',
  eligibility: 'eligibility question',
};

function UnknownsSection({
  report,
  detail,
  unknowns,
}: {
  report: NonNullable<AssessmentDetail['report']>;
  detail: AssessmentDetail;
  unknowns: UnknownsView | null;
}) {
  const noNumber = report.dimensions.flatMap((dimension) =>
    dimension.state === 'insufficient_evidence' ? [dimension] : [],
  );
  const incompleteCriteria = report.criteria.flatMap((criterion) =>
    criterion.state === 'partial' || criterion.state === 'insufficient_evidence' ? [criterion] : [],
  );
  return (
    <section aria-labelledby="unknowns-heading" data-testid="unknowns-section">
      <h2 id="unknowns-heading">Unknowns and missing information</h2>
      <p className="notice" role="note">
        Missing information is not negative evidence. Everything below is a gap in what was
        submitted or captured, not a finding against the project, and nothing was added to fill it.
      </p>

      <h3>Dimensions without a number</h3>
      {noNumber.length === 0 ? (
        <p>Every dimension had enough evidence for a number.</p>
      ) : (
        <ul>
          {noNumber.map((dimension) => (
            <li key={dimension.id}>
              <strong>{dimension.name}</strong> <code>{dimension.id}</code> —{' '}
              {INSUFFICIENCY_LABELS[dimension.reason]}
            </li>
          ))}
        </ul>
      )}

      <h3>Criteria that are incomplete</h3>
      {incompleteCriteria.length === 0 ? (
        <p>Every criterion was fully assessed.</p>
      ) : (
        <ul>
          {incompleteCriteria.map((criterion) => (
            <li key={criterion.key}>
              <strong>{criterion.name}</strong> —{' '}
              {criterion.state === 'insufficient_evidence'
                ? 'not assessed (insufficient evidence)'
                : `partly assessed (missing ${criterion.missingDimensionIds.join(', ')})`}
            </li>
          ))}
        </ul>
      )}

      <h3>Recorded limitations of this report</h3>
      {detail.limitations.length === 0 ? (
        <p>No limitations were recorded beyond those on this page.</p>
      ) : (
        <ul>
          {detail.limitations.map((item) => (
            <li key={item.code}>
              <code>{item.code}</code> ×{item.count}
              {item.subjects.length > 0 ? ` — ${item.subjects.join(', ')}` : ''}
            </li>
          ))}
        </ul>
      )}

      <h3>Gaps recorded when the project material was read</h3>
      {unknowns === null ? (
        <p role="status">The project’s recorded unknowns could not be loaded.</p>
      ) : unknowns.items.length === 0 ? (
        <p>No unknowns are recorded for this project.</p>
      ) : (
        <>
          <p>
            <small>
              Recorded in the project’s evidence graph (all readings of this project, not only this
              version), as text that is not verified.
            </small>
          </p>
          <ul>
            {unknowns.items.map((unknown) => (
              <li key={unknown.id}>
                <span className="tag">{UNKNOWN_TYPE_LABEL[unknown.unknownType]}</span>{' '}
                {unknown.text}
              </li>
            ))}
          </ul>
          {unknowns.hasMore ? (
            <p>More unknowns exist than are listed here; see the evidence graph.</p>
          ) : null}
        </>
      )}
      <p>
        <small>
          Ranking these gaps and turning them into questions is not part of this version.
        </small>
      </p>
    </section>
  );
}
